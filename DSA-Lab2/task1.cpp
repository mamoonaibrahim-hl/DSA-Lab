#include<iostream>
using namespace std;
int main()
{
    cout<<"Memory in bytes of int: "<<sizeof(int)<<endl;
    cout<<"Memory in bytes of long: "<<sizeof(long)<<endl;
    cout<<"Memory in bytes of float: "<<sizeof(float)<<endl;
    cout<<"Memory in bytes of double: "<<sizeof(double)<<endl;
    cout<<"Memory in bytes of char: "<<sizeof(char)<<endl;
    return 0;
}